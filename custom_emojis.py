def button_emoji_id(original_id: str) -> str:
    return BUTTON_EMOJI_IDS.get(str(original_id), str(original_id))


def _valid_custom_id(value: Any) -> bool:
    return isinstance(value, str) and value.isdigit()


def premiumize_text(text: Any) -> Any:
    """Convert configured fallback emojis to Telegram HTML custom emojis."""
    if not isinstance(text, str) or not text or "<tg-emoji" in text:
        return text

    configured = [
        (emoji, emoji_id)
        for emoji, emoji_id in MESSAGE_EMOJI_IDS.items()
        if _valid_custom_id(emoji_id)
    ]
    if not configured:
        return text

    # Match existing Telegram tags as one token so a shorter emoji such as
    # "❤" cannot be inserted inside a longer configured emoji or inside a
    # tag that was already produced.
    emoji_pattern = "|".join(
        re.escape(emoji)
        for emoji, _ in sorted(configured, key=lambda item: len(item[0]), reverse=True)
    )
    pattern = re.compile(r"<tg-emoji\b[^>]*>.*?</tg-emoji>|" + emoji_pattern, re.DOTALL)
    id_by_emoji = dict(configured)

    def replace(match: re.Match[str]) -> str:
        value = match.group(0)
        if value.startswith("<tg-emoji"):
            return value
        emoji_id = id_by_emoji.get(value)
        if not emoji_id:
            return value
        return f'<tg-emoji emoji-id="{emoji_id}">{value}</tg-emoji>'

    return pattern.sub(replace, text)
